"""Render Phase 5 DBML and a crow's foot PNG from the checked-in SQL, offline.

This intentionally parses only the simple DDL conventions in sql/schema.sql.
It is not a general SQL parser. No datasets or databases are written.
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def read_schema():
    sql = (ROOT / "sql/schema.sql").read_text(encoding="utf-8")
    tables = {}
    for name, body in re.findall(r"CREATE TABLE public\.(\w+) \(\n(.*?)\n\);", sql, re.S):
        columns = []
        for line in body.splitlines():
            match = re.fullmatch(r"    (\w+) (text|smallint|integer|timestamptz|boolean|double precision)( NOT NULL)?,?", line)
            if match:
                col, dtype, required = match.groups()
                columns.append((col, dtype, bool(required)))
            elif not line.startswith("    CONSTRAINT "):
                raise ValueError(f"Unrecognized DDL in {name}: {line}")
        pk = re.search(r"PRIMARY KEY \(([^)]+)\)", body).group(1).split(", ")
        unique = re.findall(r"UNIQUE \(([^)]+)\)", body)
        checks = re.findall(r"CONSTRAINT (\w+) CHECK \((.*)\),?$", body, re.M)
        refs = [(name, c.split(", "), p, pc.split(", "), False)
                for c, p, pc in re.findall(r"FOREIGN KEY \(([^)]+)\) REFERENCES public\.(\w+) \(([^)]+)\)", body)]
        tables[name] = dict(columns=columns, pk=pk, unique=unique, checks=checks, refs=refs)
    for child, c, parent, pc in re.findall(
        r"ALTER TABLE public\.(\w+) ADD CONSTRAINT \w+\n    FOREIGN KEY \(([^)]+)\) REFERENCES public\.(\w+) \(([^)]+)\) DEFERRABLE INITIALLY DEFERRED;", sql
    ):
        tables[child]["refs"].append((child, c.split(", "), parent, pc.split(", "), True))
    return tables


def dbml(tables):
    lines = ["// Generated by scripts/generate_erd.py from sql/schema.sql.",
             "// SQL is authoritative for deferred enforcement and supporting indexes.",
             "Project FoodLens {", "  database_type: 'PostgreSQL'", "}", ""]
    for name, table in tables.items():
        lines.append(f"Table {name} {{")
        for col, dtype, required in table["columns"]:
            settings = ["not null" if required else "null"]
            if table["pk"] == [col]:
                settings.append("pk")
            if col in table["unique"]:
                settings.append("unique")
            lines.append(f'  {col} "{dtype}" [{", ".join(settings)}]')
        if len(table["pk"]) > 1:
            lines.extend(["  indexes {", f'    ({", ".join(table["pk"])}) [pk]', "  }"])
        if table["checks"]:
            lines.append("  checks {")
            for constraint, expression in table["checks"]:
                lines.append(f"    `{expression}` [name: '{constraint}']")
            lines.append("  }")
        if name == "products":
            lines.append("  Note: 'Nutrition and primary-membership FKs are DEFERRABLE INITIALLY DEFERRED in SQL. Insert related rows in one transaction.'")
        lines.extend(["}", ""])
    for table in tables.values():
        for child, cols, parent, targets, deferred in table["refs"]:
            def endpoint(t, cs):
                return t + "." + (cs[0] if len(cs) == 1 else "(" + ", ".join(cs) + ")")
            if deferred:
                lines.append("// DEFERRABLE INITIALLY DEFERRED; checked at transaction commit.")
            if child == "products" and parent == "nutrition":
                # DBML disallows duplicate endpoint pairs; represent the mutual
                # FKs as one one-to-one edge and retain the reverse DDL here.
                lines.append("// Reciprocal SQL FK: products.barcode -> nutrition.barcode (required at commit).")
                continue
            relation = "-" if parent == "product_categories" or {child, parent} == {"products", "nutrition"} else ">"
            lines.append(f"Ref: {endpoint(child, cols)} {relation} {endpoint(parent, targets)}")
    return "\n".join(lines) + "\n"


def render(tables, destination):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Rectangle, Circle

    fig, ax = plt.subplots(figsize=(30, 17))
    fig.subplots_adjust(0, 0, 1, 1)
    ax.set(xlim=(0, 3000), ylim=(1700, 0))
    ax.axis("off")
    fig.patch.set_facecolor("#f3f6fa")
    ax.text(65, 65, "FOODLENS  /  PostgreSQL relational schema", fontsize=25, weight="bold", color="#142d49")
    ax.text(65, 105, "PHASE 5   •   Five tables   •   Exact CSV column mapping   •   Empty schema only", fontsize=13, color="#516479")
    layout = {"brands": (65, 185, 570), "categories": (65, 660, 570),
              "products": (820, 185, 850), "product_categories": (820, 1060, 850),
              "nutrition": (1890, 185, 1045)}
    colors = {"brands": "#366678", "categories": "#6b588b", "products": "#234b75",
              "product_categories": "#92703a", "nutrition": "#287565"}
    row_h = 27
    for name, (x, y, width) in layout.items():
        table = tables[name]
        height = 82 + row_h * len(table["columns"])
        ax.add_patch(Rectangle((x+5, y+5), width, height, color="#dce3eb", lw=0))
        ax.add_patch(Rectangle((x, y), width, height, facecolor="white", edgecolor="#c3cfdb"))
        ax.add_patch(Rectangle((x, y), width, 48, color=colors[name], lw=0))
        ax.text(x+18, y+31, name, fontsize=17, weight="bold", color="white")
        ax.text(x+width-18, y+31, f'{len(table["columns"])} columns', ha="right", fontsize=11, color="white")
        for offset, label in [(14, "KEY"), (105, "COLUMN"), (width-210, "TYPE"), (width-55, "NULL")]:
            ax.text(x+offset, y+70, label, fontsize=9, weight="bold", color="#66788c")
        foreign = {c for _, cs, _, _, _ in table["refs"] for c in cs}
        for i, (col, dtype, required) in enumerate(table["columns"]):
            top = y+82+i*row_h
            if i % 2 == 0:
                ax.add_patch(Rectangle((x+1, top), width-2, row_h, facecolor="#f2f5f8", lw=0))
            keys = ("PK " if col in table["pk"] else "") + ("FK " if col in foreign else "") + ("UQ" if col in table["unique"] else "")
            ax.text(x+14, top+18, keys.strip(), fontsize=9, weight="bold", color=colors[name])
            ax.text(x+105, top+18, col, fontsize=10.5, family="DejaVu Sans Mono", color="#1d3044")
            ax.text(x+width-210, top+18, dtype, fontsize=10, color="#4f6174")
            ax.text(x+width-40, top+18, "—" if required else "yes", ha="center", fontsize=10, color="#4f6174")

    def endpoint(point, direction, cardinality):
        x, y = point
        dx, dy = direction  # points into the connector, away from the table
        px, py = -dy, dx
        def bar(distance):
            ax.plot([x+dx*distance-px*8, x+dx*distance+px*8],
                    [y+dy*distance-py*8, y+dy*distance+py*8], color="#40556c", lw=1.5)
        if cardinality.endswith("many"):
            for offset in (-9, 0, 9):
                ax.plot([x+px*offset, x+dx*18], [y+py*offset, y+dy*18], color="#40556c", lw=1.5)
        else:
            bar(7)
        if cardinality.startswith("zero"):
            ax.add_patch(Circle((x+dx*27, y+dy*27), 6, facecolor="#f3f6fa", edgecolor="#40556c", lw=1.5))
        else:
            bar(23)

    def edge(points, start, end, label, label_xy):
        ax.plot(*zip(*points), color="#40556c", lw=1.5, zorder=0)
        for a, b, card in [(points[0], points[1], start), (points[-1], points[-2], end)]:
            dx, dy = b[0]-a[0], b[1]-a[1]
            length = (dx*dx+dy*dy)**.5
            endpoint(a, (dx/length, dy/length), card)
        ax.text(*label_xy, label, fontsize=10, ha="center", color="#40556c",
                bbox=dict(facecolor="#f3f6fa", edgecolor="none", pad=4))

    edge([(635,280),(730,280),(730,361),(820,361)], "zero-one", "zero-many", "primary brand", (727,255))
    edge([(635,755),(720,755),(720,496),(820,496)], "one-one", "zero-many", "primary category\n(provenance)", (713,605))
    edge([(1245,699),(1245,1060)], "one-one", "one-many", "memberships *", (1350,885))
    edge([(350,796),(350,1182),(820,1182)], "one-one", "zero-many", "category memberships", (535,1159))
    edge([(1670,285),(1890,285)], "one-one", "one-one", "nutrition *", (1780,263))

    ax.text(65, 1320, "RELATIONSHIP KEY", fontsize=13, weight="bold", color="#234b75")
    ax.text(65, 1360, "Circle = zero   |   Bar = one   |   Crow’s foot = many", fontsize=12, color="#40556c")
    ax.text(65, 1390, "PK = primary key   •   FK = foreign key   •   UQ = unique\nNULL — = NOT NULL; yes = nullable", fontsize=12, color="#40556c", linespacing=1.8, va="top")
    ax.text(65, 1490, "* At commit: reciprocal barcode FKs enforce exactly one nutrition row.\nThe deferred (barcode, primary_category_id) FK requires a primary membership.\nThe five connectors summarize all seven SQL foreign keys.", fontsize=12, color="#40556c", linespacing=1.7, va="top")
    ax.text(65, 1635, "Nutrients remain nullable; reported text and review flags are preserved.  |  Full CHECK expressions and deferred FK details: sql/schema.sql", fontsize=11, color="#66788c")
    fig.savefig(destination, dpi=140, facecolor=fig.get_facecolor())
    plt.close(fig)


if __name__ == "__main__":
    schema = read_schema()
    (ROOT / "reports/erd.dbml").write_text(dbml(schema), encoding="utf-8")
    render(schema, ROOT / "reports/erd.png")
    print(f"Generated ERD: {len(schema)} tables, {sum(len(t['columns']) for t in schema.values())} columns, 7 foreign keys.")
